from collections import Counter


def count_letters(text):
    """Возвращает словарь с подсчитанными буквами в тексте (нижний регистр)."""
    text = text.lower()  # Приводим текст к нижнему регистру
    letter_counts = Counter(char for char in text if char.isalpha())  # Подсчитываем только буквы
    return dict(letter_counts)


def calculate_frequency(letter_counts):
    """Возвращает словарь с частотой каждой буквы, округленной до двух знаков."""
    # Все буквы русского алфавита в нужном порядке
    russian_alphabet = 'у л к о м р ь я д б з е ё н ы й а т ц п и ч ю в с х г ш ж щ'.split()

    total_letters = sum(letter_counts.values())  # Общее количество букв

    # Округляем частоту каждой буквы до двух знаков
    letter_frequencies = {letter: round(letter_counts.get(letter, 0) / total_letters, 2)
                          for letter in russian_alphabet}

    return letter_frequencies


# Текст для анализа
main_str = """
У лукоморья дуб зелёный;
Златая цепь на дубе том:
И днём и ночью кот учёный
Всё ходит по цепи кругом;
Идёт направо — песнь заводит,
Налево — сказку говорит.
Там чудеса: там леший бродит,
Русалка на ветвях сидит;
Там на неведомых дорожках
Следы невиданных зверей;
Избушка там на курьих ножках
Стоит без окон, без дверей;
Там лес и дол видений полны;
Там о заре прихлынут волны
На брег песчаный и пустой,
И тридцать витязей прекрасных
Чредой из вод выходят ясных,
И с ними дядька их морской;
Там королевич мимоходом
Пленяет грозного царя;
Там в облаках перед народом
Через леса, через моря
Колдун несёт богатыря;
В темнице там царевна тужит,
А бурый волк ей верно служит;
Там ступа с Бабою Ягой
Идёт, бредёт сама собой,
Там царь Кащей над златом чахнет;
Там русский дух… там Русью пахнет!
И там я был, и мёд я пил;
У моря видел дуб зелёный;
Под ним сидел, и кот учёный
Свои мне сказки говорил.
"""

# Подсчет букв
letter_counts = count_letters(main_str)

# Вычисление частот
letter_frequencies = calculate_frequency(letter_counts)

# Вывод частот
for letter, frequency in letter_frequencies.items():
    print(f"{letter}: {frequency:.2f}")  # Убедимся, что форматируем вывод с двумя знаками после запятой
